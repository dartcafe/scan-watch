#!/usr/bin/env python3
"""Collect translatable texts and update scan_watch/locale/*.po.

Python: the first argument of _("...") calls (string literals only).
Web page: t("...") and N_("...") in the script, and elements with a data-t
attribute (their text, whitespace collapsed).

    python3 tools/update_po.py          # write messages.pot, merge into every <lang>.po
    python3 tools/update_po.py --check  # exit 1 if a catalog is missing or out of date

New texts get an empty msgstr, texts no longer used are dropped. Fill in the
empty msgstr entries (any .po editor works) and run the tests.
"""

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "scan_watch"
LOCALE = PACKAGE / "locale"
sys.path.insert(0, str(ROOT))

from scan_watch.i18n import parse_po  # noqa: E402

JS_CALL = re.compile(r'\b(?:t|N_)\(\s*"((?:[^"\\]|\\.)*)"')
DATA_T = re.compile(r"<(\w+)[^>]*\bdata-t\b[^>]*>([^<]*)</\1>")


def python_texts(path):
    tree = ast.parse(path.read_text("utf-8"), str(path))
    for node in ast.walk(tree):
        if (isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == "_"
                and node.args and isinstance(node.args[0], ast.Constant) and isinstance(node.args[0].value, str)):
            yield node.args[0].value, node.lineno


def page_texts(path):
    text = path.read_text("utf-8")
    for m in JS_CALL.finditer(text):
        yield ast.literal_eval(f'"{m.group(1)}"'), text.count("\n", 0, m.start()) + 1
    for m in DATA_T.finditer(text):
        yield " ".join(m.group(2).split()), text.count("\n", 0, m.start()) + 1


def collect():
    """msgid -> files using it, in order of first appearance.

    No line numbers, so catalogs only change when texts do.
    """
    found = {}
    sources = [(p, python_texts) for p in sorted(PACKAGE.rglob("*.py"))]
    sources += [(p, page_texts) for p in sorted((PACKAGE / "static").glob("*.html"))]
    for path, reader in sources:
        for msgid, _line in sorted(reader(path), key=lambda item: item[1]):
            refs = found.setdefault(msgid, [])
            if msgid and str(path.relative_to(ROOT)) not in refs:
                refs.append(str(path.relative_to(ROOT)))
    return found


def quote(text):
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t")
    lines = escaped.split("\n")
    if len(lines) == 1:
        return f'"{escaped}"'
    parts = [f'"{line}\\n"' for line in lines[:-1]] + ([f'"{lines[-1]}"'] if lines[-1] else [])
    return '""\n' + "\n".join(parts)


def write_catalog(found, translations, header):
    out = [header.rstrip("\n"), ""]
    for msgid, refs in found.items():
        out.append("#: " + " ".join(refs))
        if "{" in msgid:
            out.append("#, python-brace-format")
        out.append(f"msgid {quote(msgid)}")
        out.append(f"msgstr {quote(translations.get(msgid, ''))}")
        out.append("")
    return "\n".join(out)


POT_HEADER = '''# Translatable texts of scan-watch. Generated by tools/update_po.py, do not edit.
# New language: copy to <lang>.po, set "Language", run tools/update_po.py, translate.
msgid ""
msgstr ""
"Project-Id-Version: scan-watch\\n"
"Language: \\n"
"MIME-Version: 1.0\\n"
"Content-Type: text/plain; charset=UTF-8\\n"
"Content-Transfer-Encoding: 8bit\\n"
'''


def po_header(existing):
    """The header entry of an existing catalog, kept as it is."""
    first = existing.split("\n\n", 1)[0]
    return first if 'msgid ""' in first else POT_HEADER


def main():
    check = "--check" in sys.argv[1:]
    found = collect()
    outputs = {LOCALE / "messages.pot": write_catalog(found, {}, POT_HEADER)}
    for po in sorted(LOCALE.glob("*.po")):
        existing = po.read_text("utf-8")
        translations = {msgid: msgstr for msgid, msgstr, fuzzy in parse_po(existing) if msgid}
        outputs[po] = write_catalog(found, translations, po_header(existing))
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text("utf-8") != text]
    if check:
        for p in stale:
            print(f"{p.relative_to(ROOT)} is out of date, run tools/update_po.py")
        return 1 if stale else 0
    LOCALE.mkdir(exist_ok=True)
    for p in stale:
        p.write_text(outputs[p], "utf-8")
        print(f"updated {p.relative_to(ROOT)}")
    for po in sorted(LOCALE.glob("*.po")):
        missing = [m for m, s, f in parse_po(po.read_text("utf-8")) if m and not s]
        if missing:
            print(f"{po.relative_to(ROOT)}: {len(missing)} untranslated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
